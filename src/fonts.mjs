/**
 * Downloads Inter + Poppins (latin subsets) from Google Fonts and writes a
 * self-hosted @font-face stylesheet at src/fonts.css.
 *
 * Inter is served as one variable file (weight axis), Poppins as discrete
 * static weights. Files are de-duplicated by content hash, so a family that
 * returns the same bytes for several weights is declared once with a range.
 *
 * Run with: node src/fonts.mjs
 */
import { mkdir, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";

const OUT_DIR = path.resolve("public/assets/fonts");
const CSS_OUT = path.resolve("src/fonts.css");
const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36";

const FAMILIES = [
  {
    name: "Inter",
    query: "family=Inter:wght@400..700",
    keep: ["latin"],
    variable: true,
  },
  {
    name: "Poppins",
    query: "family=Poppins:wght@500;600;700",
    keep: ["latin"],
    variable: false,
  },
];

async function fetchText(url) {
  const res = await fetch(url, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`${url} -> HTTP ${res.status}`);
  return res.text();
}

function parseBlocks(css) {
  const blocks = [];
  const re = /\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*\{([\s\S]*?)\}/g;
  let m;
  while ((m = re.exec(css)) !== null) blocks.push({ subset: m[1], body: m[2] });
  return blocks;
}

function prop(body, name) {
  const m = body.match(new RegExp(`${name}:\\s*([^;]+);`));
  return m ? m[1].trim() : "";
}

async function main() {
  await mkdir(OUT_DIR, { recursive: true });

  /* key: family|style|hash -> { file, weights:Set<string>, range } */
  const files = new Map();

  for (const family of FAMILIES) {
    const css = await fetchText(`https://fonts.googleapis.com/css2?${family.query}&display=swap`);

    for (const block of parseBlocks(css).filter((b) => family.keep.includes(b.subset))) {
      const style = prop(block.body, "font-style") || "normal";
      const range = prop(block.body, "unicode-range");
      const weight = family.variable ? "variable" : prop(block.body, "font-weight") || "400";
      const srcMatch = block.body.match(/url\((https:\/\/[^)]+)\)/);
      if (!srcMatch) continue;

      const res = await fetch(srcMatch[1], { headers: { "User-Agent": UA } });
      if (!res.ok) throw new Error(`${srcMatch[1]} -> HTTP ${res.status}`);
      const buf = Buffer.from(await res.arrayBuffer());
      const hash = createHash("sha1").update(buf).digest("hex").slice(0, 8);
      const key = `${family.name}|${style}|${hash}`;

      if (!files.has(key)) {
        const fileName = `${family.name.toLowerCase()}-${style}-${weight}.woff2`;
        files.set(key, { file: fileName, weights: new Set(), range, family, style });
        await writeFile(path.join(OUT_DIR, fileName), buf);
        //console.log(`saved ${fileName} (${(buf.length / 1024).toFixed(1)} KB)`);
      }
      files.get(key).weights.add(family.variable ? "400 700" : weight);
    }
  }

  const faces = [];
  for (const entry of files.values()) {
    const weights = [...entry.weights].sort();
    faces.push(
      [
        "@font-face {",
        `  font-family: "${entry.family.name}";`,
        `  font-style: ${entry.style};`,
        `  font-weight: ${weights.join(", ")};`,
        "  font-display: swap;",
        `  src: url("/assets/fonts/${entry.file}") format("woff2");`,
        entry.range ? `  unicode-range: ${entry.range};` : null,
        "}",
      ]
        .filter(Boolean)
        .join("\n"),
    );
  }

  const header = [
    "/* Generated by src/fonts.mjs — self-hosted Inter and Poppins (latin subsets). */",
    "",
  ].join("\n");
  await writeFile(CSS_OUT, header + faces.join("\n\n") + "\n");
  //console.log(`wrote ${CSS_OUT} with ${faces.length} @font-face rules`);
}

main().catch((err) => {
  //console.error("font download failed:", err.message);
  process.exit(1);
});
